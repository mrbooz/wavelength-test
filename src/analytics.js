// Analytics dashboard helpers - all the aggregations in one place.

export function metric1(rows) {
  let total = 0;
  for (const r of rows) {
    if (r && typeof r.value1 === "number") {
      total += r.value1;
    }
  }
  const count = rows.length || 1;
  return { total, average: total / count, label: "metric1" };
}

